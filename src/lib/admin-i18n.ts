const FIXED_PAGE: Record<string, AdminKey> = {
  '/': 'page.home', '/blog': 'page.blog', '/upgrade': 'page.upgrade', '/register': 'page.register', '/login': 'page.login',
  '/customers': 'page.customers', '/about': 'page.about', '/updates': 'page.updates', '/contact': 'page.contact',
  '/privacy': 'page.privacy', '/terms': 'page.terms', '/tutors': 'page.tutors', '/onboarding': 'page.onboarding', '/dashboard': 'page.dashboard',
}
/** The in-app sections the journey records (the same list as src/lib/track-path.ts; a test keeps them equal). */
export const JOURNEY_APP_SECTIONS: readonly string[] = [
  'dashboard', 'students', 'lessons', 'calendar', 'messages', 'reports', 'team', 'payments',
  'packages', 'coupons', 'subscriptions', 'waitlist', 'availability', 'ai', 'import',
  'referral', 'developers', 'settings', 'upgrade',
]

/** A readable name for a recorded path; the English version is the same text as pageLabel() in timeline.ts. */
export function pageLabelText(t: AdminT, path: string | null | undefined): string {
  if (!path) return t('page.unknown')
  if (FIXED_PAGE[path]) return t(FIXED_PAGE[path])
  if (path.startsWith('/blog/')) return t('page.blogPost', { title: path.slice('/blog/'.length).replace(/-/g, ' ') })
  const section = path.slice(1)
  if (JOURNEY_APP_SECTIONS.includes(section)) return t('page.inApp', { section })
  return path
}

