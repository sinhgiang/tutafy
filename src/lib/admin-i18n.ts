export const ADMIN_DICTIONARIES: Record<AdminLang, Record<AdminKey, string>> = { en: EN, vi: VI }

export type AdminT = (key: AdminKey, params?: Record<string, string | number>) => string

/** Fills {name} placeholders; a placeholder with no value is left as it is, so a mistake shows instead of hiding. */
export function fill(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}

export function makeT(lang: AdminLang, dictionaries: Record<AdminLang, Record<AdminKey, string>> = ADMIN_DICTIONARIES): AdminT {
  const dict = dictionaries[lang] ?? dictionaries[DEFAULT_ADMIN_LANG]
  return (key, params) => fill(dict[key] ?? dictionaries[DEFAULT_ADMIN_LANG][key] ?? key, params)
}

