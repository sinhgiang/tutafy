const READ_ERROR_VISITOR_TABLES = ['visitors', 'visitor_events']

/** One sentence naming every table that could not be read; the English version is the same text as read-errors.ts. */
export function readErrorText(t: AdminT, tables: string[]): string {
  const unique = [...new Set(tables)]
  if (unique.length === 0) return t('readError.some')
  const names = unique.map(tb => (tb in EN_TABLES ? t(EN_TABLES[tb]) : t('table.other', { name: tb })))
  const joined = names.length <= 1 ? names.join('') : `${names.slice(0, -1).join(', ')}${t('readError.and')}${names[names.length - 1]}`
  const visitorOnly = unique.every(tb => READ_ERROR_VISITOR_TABLES.includes(tb))
  return t('readError.tables', { names: joined, it: unique.length === 1 ? t('readError.it') : t('readError.them'), hint: visitorOnly ? t('readError.hintVisitors') : t('readError.hintOther') })
}
