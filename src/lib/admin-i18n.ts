// Every word the owner's admin pages print, in the two languages the owner can switch between (EN | VI), in ONE place.
// The admin pages (/admin, /super-admin and every page under them) ask for a key; they never carry a sentence of their own.
// English is the default. This file is the only file in src that may hold Vietnamese: tests/no-vietnamese.test.ts fails when
// Vietnamese text turns up anywhere else, and tests/admin-i18n.test.ts fails when a key is missing in one language, when the two
// versions of a key do not take the same {placeholders}, or when a key is never used. No imports from the app, so the node tests
// can load it. Numbers, dates, money, plan names (Free, Pro, Academy), brand names (Polar, Stripe, ChatGPT) and country names
// are not translated.

export const ADMIN_LANGS = ['en', 'vi'] as const
export type AdminLang = (typeof ADMIN_LANGS)[number]
export const DEFAULT_ADMIN_LANG: AdminLang = 'en'
/** The cookie that remembers the choice in the owner's browser (read on the server, so the page arrives in the right language). */
export const ADMIN_LANG_COOKIE = 'tutafy_admin_lang'

export function normalizeAdminLang(value: unknown): AdminLang {
  return value === 'vi' ? 'vi' : DEFAULT_ADMIN_LANG
}

